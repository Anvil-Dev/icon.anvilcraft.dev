// Generates src/font-metrics.ts: exact Inter advance widths (em fractions)
// for printable ASCII, extracted from the bundled @fontsource/inter files.
// Run with: node scripts/gen-font-metrics.mjs
import { readFileSync, writeFileSync } from "node:fs";
import opentype from "opentype.js";

const WEIGHTS = [500, 800];
const FIRST = 32; // space
const LAST = 126; // ~

const tables = {};
for (const weight of WEIGHTS) {
  const buf = readFileSync(`node_modules/@fontsource/inter/files/inter-latin-${weight}-normal.woff`);
  const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
  const widths = [];
  for (let code = FIRST; code <= LAST; code++) {
    const glyph = font.charToGlyph(String.fromCharCode(code));
    widths.push(Number((glyph.advanceWidth / font.unitsPerEm).toFixed(4)));
  }
  tables[weight] = widths;
}

const rows = (arr) =>
  Array.from({ length: Math.ceil(arr.length / 19) }, (_, i) =>
    `    ${arr.slice(i * 19, (i + 1) * 19).join(", ")},`,
  ).join("\n");

const output = `// Generated by scripts/gen-font-metrics.mjs — do not edit by hand.
// Exact Inter advance widths as em fractions for char codes 32..126,
// indexed by [code - 32]. Weights 500 (badge title) and 800 (badge value).
export const INTER_ASCII_WIDTHS = {
  500: [
${rows(tables[500])}
  ],
  800: [
${rows(tables[800])}
  ],
} as const;
`;

writeFileSync("src/font-metrics.ts", output);
console.log("src/font-metrics.ts written");
